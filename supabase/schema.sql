-- ============================================================
-- BYR · Depuración semanal de inventario
-- Esquema para Supabase (Postgres + Auth + RLS)
--
-- Ejecuta este archivo completo en:
--   Supabase Dashboard → SQL Editor → New query → Run
--
-- El script es idempotente: puedes volver a ejecutarlo sin
-- perder los cortes ya guardados.
-- ============================================================

create extension if not exists pgcrypto;

-- ------------------------------------------------------------
-- 1. Cabecera de cada corte semanal
-- ------------------------------------------------------------
create table if not exists public.cortes (
  id                uuid primary key default gen_random_uuid(),
  user_id           uuid not null default auth.uid() references auth.users (id) on delete cascade,
  fecha_corte       date not null,
  archivo_sistema   text not null default '',
  archivo_fisico    text not null default '',
  total_sistema     integer not null default 0 check (total_sistema >= 0),
  total_fisico      integer not null default 0 check (total_fisico >= 0),
  total_eliminar    integer not null default 0 check (total_eliminar >= 0),
  total_incluir     integer not null default 0 check (total_incluir >= 0),
  total_excluidas   integer not null default 0 check (total_excluidas >= 0),
  total_ok          integer not null default 0 check (total_ok >= 0),
  total_anomalias   integer not null default 0 check (total_anomalias >= 0),
  notas             text not null default '',
  created_at        timestamptz not null default now()
);

-- Migración para bases de datos creadas con la versión anterior:
alter table public.cortes add column if not exists total_excluidas integer not null default 0;
alter table public.cortes drop column if exists total_revisar;

comment on table public.cortes is
  'Resumen de cada corte semanal de inventario (sistema vs conteo físico).';

-- ------------------------------------------------------------
-- 2. Detalle placa por placa de cada corte
-- ------------------------------------------------------------
create table if not exists public.cortes_detalle (
  id              bigint generated by default as identity primary key,
  corte_id        uuid not null references public.cortes (id) on delete cascade,
  user_id         uuid not null default auth.uid() references auth.users (id) on delete cascade,
  placa           text not null,
  placa_norm      text not null,
  estado          text not null check (estado in ('ELIMINAR', 'INCLUIR', 'OK', 'EXCLUIDA')),
  taller_sistema  text not null default '',
  taller_fisico   text not null default '',
  tipo            text not null default '',
  codigo_r        text not null default '',
  observacion     text not null default ''
);

comment on table public.cortes_detalle is
  'Placas comparadas de un corte. Se borran en cascada con su cabecera.';

-- Migración del check de estados para bases de datos anteriores:
alter table public.cortes_detalle drop constraint if exists cortes_detalle_estado_check;
alter table public.cortes_detalle add constraint cortes_detalle_estado_check
  check (estado in ('ELIMINAR', 'INCLUIR', 'OK', 'EXCLUIDA'));

-- ------------------------------------------------------------
-- 3. Índices para las consultas de la app
-- ------------------------------------------------------------
create index if not exists cortes_user_fecha_idx
  on public.cortes (user_id, fecha_corte desc, created_at desc);

create index if not exists cortes_detalle_corte_idx
  on public.cortes_detalle (corte_id, estado);

create index if not exists cortes_detalle_corte_placa_idx
  on public.cortes_detalle (corte_id, placa_norm);

-- ------------------------------------------------------------
-- 4. RLS: cada usuario ve y administra únicamente sus cortes
-- ------------------------------------------------------------
alter table public.cortes enable row level security;
alter table public.cortes_detalle enable row level security;

drop policy if exists "cortes_select_own" on public.cortes;
create policy "cortes_select_own"
  on public.cortes for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "cortes_insert_own" on public.cortes;
create policy "cortes_insert_own"
  on public.cortes for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "cortes_delete_own" on public.cortes;
create policy "cortes_delete_own"
  on public.cortes for delete
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "detalle_select_own" on public.cortes_detalle;
create policy "detalle_select_own"
  on public.cortes_detalle for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "detalle_insert_own" on public.cortes_detalle;
create policy "detalle_insert_own"
  on public.cortes_detalle for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "detalle_delete_own" on public.cortes_detalle;
create policy "detalle_delete_own"
  on public.cortes_detalle for delete
  to authenticated
  using (auth.uid() = user_id);

-- ------------------------------------------------------------
-- 5. Permisos para el rol autenticado (RLS sigue filtrando filas)
-- ------------------------------------------------------------
grant usage on schema public to authenticated;
grant select, insert, delete on public.cortes to authenticated;
grant select, insert, delete on public.cortes_detalle to authenticated;
grant usage, select on all sequences in schema public to authenticated;

